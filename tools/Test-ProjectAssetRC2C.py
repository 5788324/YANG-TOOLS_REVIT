#!/usr/bin/env python3
"""RC2C source contract and UI wiring checks. Does not execute Revit / C#."""
from pathlib import Path
import xml.etree.ElementTree as ET
import json,re,sys
p=Path(__file__).resolve().parents[1]
w=(p/'src/YangTools.Revit/UI/ProjectAssetManagerWindow.xaml.cs').read_text(encoding='utf-8-sig')
x=(p/'src/YangTools.Revit/UI/ProjectAssetManagerWindow.xaml').read_text(encoding='utf-8-sig')
s=(p/'src/YangTools.Revit/Core/ProjectAssets/ProjectAssetExcelImportService.cs').read_text(encoding='utf-8')
checks=[]
def check(label,passed):checks.append((label,bool(passed)))
def between(src,a,b):return src[src.index(a):src.index(b,src.index(a))]
ui=between(w,'private void ImportExcel_Click(', 'private bool IsProjectInfoParameterView()')
svc=between(s,'internal static ProjectAssetExcelImportResult Execute(', '\n        private static bool ApplyRow(')
apply=between(s,'private static bool ApplyRow(', '\n        private static bool TryGetAssetId(')
root=ET.fromstring(x)
check('XAML XML parsed',root.tag.endswith('Window'))
check('Excel import Button bound once',len([e for e in root.iter() if e.attrib.get('Click')=='ImportExcel_Click'])==1)
check('WPF event handler present once',w.count('private void ImportExcel_Click(')==1)
check('UI keeps project info protection', 'IsProjectInfoParameterView()' in ui)
check('UI keeps dialog', 'ExcelService.ShowOpenDialog()' in ui)
check('UI snapshot file rows before Revit ExternalEvent',ui.index('ExcelService.ReadExcel(filePath)')<ui.index('_handler.SetAction('))
check('UI copies each row', 'new Dictionary<string, object>(row)' in ui)
check('UI shows Excel reading error', '读取 Excel 失败' in ui)
check('UI captures tab name', 'var tabAtRequest = _currentTabName;' in ui)
check('UI captures version', 'var tabVersionAtRequest = _tabLoadVersion;' in ui)
check('UI captures selected node', 'var nodeAtRequest = _selectedNode;' in ui)
check('UI gates closed window', 'if (_isClosed) return;' in ui)
check('UI gates outdated tab', 'tabVersionAtRequest != _tabLoadVersion' in ui and '_currentTabName != tabAtRequest' in ui)
check('UI gates changed node', 'ReferenceEquals(_selectedNode, nodeAtRequest)' in ui)
check('UI retains existing ExternalEvent', '_handler.SetAction(app =>' in ui and '_externalEvent.Raise();' in ui)
check('UI does not touch wrong ActiveUIDocument', 'app.ActiveUIDocument.Document' not in ui)
check('UI binds to initial Document', 'ProjectAssetExcelImportService.Execute(_doc, request)' in ui)
check('UI refreshes data when current', 'LoadData();' in ui)
check('UI conditional one undo message', 'result.ChangedCount > 0' in ui and '未创建撤销记录' in ui)
check('UI no success on exceptions', 'catch (Exception ex)' in ui and '导入失败（整批已取消）' in ui)
check('UI explicit skip summary', 'result.SkippedCount' in ui and 'result.Warnings' in ui)
check('UI no direct model transaction', 'new Transaction(' not in ui and 'TransactionGroup' not in ui)
check('UI no direct element mutation', 'element.Name =' not in ui)
check('UI row helper logic moved', 'private static bool TryGetAssetId(' not in ui)
check('Service namespace', 'namespace YangTools.Revit.Core.ProjectAssets' in s)
check('Service no WPF', 'System.Windows' not in s and 'TaskDialog' not in s and 'Dispatcher' not in s)
check('Typed request', 'class ProjectAssetExcelImportRequest' in s)
check('Typed result', 'class ProjectAssetExcelImportResult' in s)
for name in ('ChangedCount','UnchangedCount','SkippedCount','Warnings'):
    check('Result field '+name, name in s)
check('Guard document validity', '!document.IsValidObject' in svc)
check('Guard readonly', 'document.IsReadOnly' in svc)
check('Guard request null', 'if (request == null)' in svc)
check('Invalid IDs explicitly counted', 'result.SkippedCount++' in svc and 'result.Warnings.Add(' in svc)
check('Duplicate IDs rejected', 'if (!seenIds.Add(idValue))' in svc)
check('Missing elements rejected', 'element == null || !element.IsValidObject' in svc)
check('Preflight before opening group', svc.index('for (int i = 0; i < input.Count; i++)') < svc.index('new TransactionGroup('))
check('Empty plan no transaction', 'if (plan.Count == 0) return result;' in svc)
check('Exactly one transaction group constructor',svc.count('new TransactionGroup(')==1)
check('No project deletion', 'document.Delete(' not in s and 'ElementTransformUtils' not in s)
check('One transaction per row',svc.count('new Transaction(document,')==1)
check('Transaction Start status checked', 'transaction.Start() != TransactionStatus.Started' in svc)
check('Transaction Commit status checked', 'transaction.Commit() != TransactionStatus.Committed' in svc)
check('No-change row rolled back', 'transaction.RollBack() != TransactionStatus.RolledBack' in svc)
check('Zero changed rows rollback group', 'if (result.ChangedCount == 0)' in svc and 'group.RollBack()' in svc)
check('Changed rows group assimilated', 'group.Assimilate() != TransactionStatus.Committed' in svc)
check('Group rollback after exceptions', 'if (group.GetStatus() == TransactionStatus.Started)' in svc and 'group.RollBack()' in svc)
check('Rollback failure distinguished', '回滚未能确认' in svc)
check('Error line number', 'row.ExcelLine' in svc)
check('Error ID', 'row.ElementIdValue' in svc)
check('Name change uses exact comparison', 'StringComparison.Ordinal' in apply and 'row.Element.Name = newName;' in apply)
check('Missing parameters fail', 'if (parameter == null)' in apply and 'throw new InvalidOperationException' in apply)
check('Readonly parameters fail', 'if (parameter.IsReadOnly)' in apply and 'throw new InvalidOperationException' in apply)
check('No silent TrySet failure', '!ParameterValueHelper.TrySetFromDisplayValue(' in apply and 'throw new InvalidOperationException' in apply)
for alias in ('图元 ID','图元ID','元素ID','名称','资产名称'):
    check('Existing Excel column alias '+alias, f'"{alias}"' in s)
check('No change to bulk rename service', (p/'src/YangTools.Revit/Core/ProjectAssets/ProjectAssetBatchRenameService.cs').is_file())
check('MCP bridge exists', (p/'src/YangTools.Revit/Mcp/RevitExecutionBroker.cs').is_file())
check('UI XAML asset grids preserved', 'AssetDataGrid' in x and 'AssetTreeView' in x)
failed=[k for k,ok in checks if not ok]
print(json.dumps({'suite':'RC2C ProjectAsset Excel import UI/atomic static contracts','total':len(checks),'passed':len(checks)-len(failed),'failed':failed,'limitation':'Static source assertions only; not a C# build, Revit loaded UI test, or Transaction runtime validation'},ensure_ascii=False,indent=2))
sys.exit(0 if not failed else 1)
